// OPT.AI Developer Hub V1.1 -- takes the SYNTHETIC fixtures computed by the OPT.AI guide's own code into this PUBLIC repository:
//   OPT-AI: scripts/demo_hub/devhub_fixtures.py synthetic <outside dir>
//   here:   node tools/sync-fixtures.mjs <outside dir>
// Writes docs/assets/devhub/data/testcases.js, data/recordings.js and docs/assets/devhub/fixtures.js (ES modules: the page fetches
// no data file) and tests/devhub/fixtures/structure_synthetic.json. Refuses to write anything that is not marked synthetic or that
// the public-safe guard (tools/public-safe-guard.mjs) rejects. Real answers, expectations and rule-set structures stay in the
// private OPT-AI repository (scripts/demo_hub/devhub_private/) -- they never come here.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scanEntries } from "./public-safe-guard.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2];
if (!source) {
  console.error("usage: node tools/sync-fixtures.mjs <output dir of devhub_fixtures.py synthetic>");
  process.exit(2);
}
const read = (name) => JSON.parse(readFileSync(join(source, name), "utf8"));
const testcases = read("testcases.json");
const recordings = read("recordings.json");
const archive = read("archive.json");
const synthetic = read("structure_synthetic.json");
const refuse = (why) => {
  console.error(`REFUSED: ${why} -- nothing written`);
  process.exit(1);
};
for (const [name, content] of Object.entries({ testcases, recordings, archive })) {
  if (!content._meta || content._meta.synthetic !== true) refuse(`${name} is not marked synthetic (only the output of devhub_fixtures.py synthetic)`);
}

const module = (header, data) => `${header}\nexport default ${JSON.stringify(data, null, 1)};\n`;
const outputs = {
  "docs/assets/devhub/data/testcases.js": module(
    "// OPT.AI Developer Hub -- the synthetic regression cases (ZZ test data, generated " + testcases._meta.expected_as_of + "): requests and\n" +
    "// expectations computed by the OPT.AI guide over synthetic answers -- no live data. Regenerate: tools/sync-fixtures.mjs (README).",
    testcases),
  "docs/assets/devhub/data/recordings.js": module(
    "// OPT.AI Developer Hub -- the synthetic answers of the regression cases (Rules API v1 format, ZZ test data, generated " +
    recordings._meta.recorded_at + "),\n// loaded only for the offline mode and the synthetic runs. `__agreements__` is the synthetic GET /v1/agreements answer.\n" +
    "// No live data. Regenerate: tools/sync-fixtures.mjs.",
    recordings),
  "docs/assets/devhub/fixtures.js":
    "// OPT.AI Developer Hub -- the example answers of the section \"Beispielantworten\": SYNTHETIC (ZZ) answers in the Rules API v1\n" +
    "// format, generated by OPT-AI scripts/demo_hub/devhub_fixtures.py synthetic. Since V1.1 they replace the archived live answers of\n" +
    "// 2026-08-22 (those remain in the Git history only). Rendered through the same panels as a live answer. Regenerate: tools/sync-fixtures.mjs.\n" +
    `export const FIXTURES = ${JSON.stringify(archive.fixtures, null, 1)};\n`,
  "tests/devhub/fixtures/structure_synthetic.json": JSON.stringify(synthetic, null, 1) + "\n",
};
const findings = scanEntries(Object.entries(outputs).map(([path, text]) => ({ path, content: Buffer.from(text, "utf8") })));
if (findings.length) {
  for (const f of findings.slice(0, 20)) console.error(`  ${f.rule}  ${f.path}:${f.line}  ${f.message}`);
  refuse(`${findings.length} public-safe finding(s)`);
}
for (const [path, text] of Object.entries(outputs)) writeFileSync(join(ROOT, path), text);
console.log(`synced (synthetic): ${testcases.cases.length} test cases, ${Object.keys(recordings.recordings).length} answers, ` +
  `${Object.keys(archive.fixtures).length} example answers, ${synthetic.cases.length} synthetic structures -- public-safe guard PASS`);
